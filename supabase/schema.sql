-- ============================================================================
-- 1. PROFILES TABLE
-- ============================================================================

create table if not exists public.profiles (
  id uuid references auth.users(id) on delete cascade primary key,
  full_name text,
  avatar_url text,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);


-- ============================================================================
-- 2. SUBJECTS TABLE
-- ============================================================================

create table if not exists public.subjects (
  id bigint generated by default as identity primary key,
  name text not null,
  code text,
  semester integer not null check (semester >= 1 and semester <= 8),
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- Prevent duplicate subject codes.
-- NULL codes are still allowed.

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'unique_subject_code'
      and conrelid = 'public.subjects'::regclass
  ) then
    alter table public.subjects
    add constraint unique_subject_code unique (code);
  end if;
end $$;


-- ============================================================================
-- 3. TOPICS TABLE
-- ============================================================================

create table if not exists public.topics (
  id bigint generated by default as identity primary key,
  subject_id bigint references public.subjects(id) on delete cascade not null,
  name text not null,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- A subject cannot have duplicate topic names.

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'unique_subject_topic'
      and conrelid = 'public.topics'::regclass
  ) then
    alter table public.topics
    add constraint unique_subject_topic unique (subject_id, name);
  end if;
end $$;


-- ============================================================================
-- 4. RESOURCES TABLE
-- ============================================================================

create table if not exists public.resources (
  id bigint generated by default as identity primary key,
  title text not null,
  url text not null,
  type text not null check (
    type in ('video', 'pdf', 'article', 'notes', 'github', 'other')
  ),
  description text,
  subject_id bigint references public.subjects(id) on delete cascade not null,
  topic_id bigint references public.topics(id) on delete set null,
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null
);


-- ============================================================================
-- 5. REVIEWS TABLE
-- ============================================================================

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  resource_id bigint references public.resources(id) on delete cascade not null,
  user_id uuid references public.profiles(id) on delete cascade default auth.uid() not null,
  rating integer not null check (rating >= 1 and rating <= 5),
  comment text,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  updated_at timestamptz default timezone('utc'::text, now()) not null,
  constraint unique_resource_user_review unique (resource_id, user_id)
);


-- ============================================================================
-- 6. BOOKMARKS TABLE
-- ============================================================================

create table if not exists public.bookmarks (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade default auth.uid() not null,
  resource_id bigint references public.resources(id) on delete cascade not null,
  created_at timestamptz default timezone('utc'::text, now()) not null,
  constraint unique_user_resource_bookmark unique (user_id, resource_id)
);


-- ============================================================================
-- 7. RESOURCE STATS VIEW
-- ============================================================================

create or replace view public.resource_stats as
select
  r.id,
  r.title,
  r.url,
  r.type,
  r.description,
  r.subject_id,
  r.topic_id,
  r.created_by,
  r.created_at,
  r.updated_at,
  coalesce(round(avg(rv.rating)::numeric, 1), 0.0) as avg_rating,
  count(rv.id)::integer as review_count
from public.resources r
left join public.reviews rv on rv.resource_id = r.id
group by r.id;

-- Apply underlying-table permissions and RLS as the querying user.
alter view public.resource_stats set (security_invoker = true);


